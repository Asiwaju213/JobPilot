/**  
 * Profile request validation schemas.
 *
 * Uses Zod (already a project dependency) for runtime validation.
 * Fields mirror the existing Prisma Profile model — no new fields invented.
 */

import { z } from "zod";

// ── Editable string fields (nullable in Prisma, optional in PATCH) ──────────

const optionalString = z
  .string()
  .trim()
  .max(500, "Must be at most 500 characters")
  .nullable()
  .optional();

const optionalText = z
  .string()
  .trim()
  .max(2000, "Must be at most 2000 characters")
  .nullable()
  .optional();

// ── Create profile ──────────────────────────────────────────────────────────

export const createProfileSchema = z.object({
  name: z
    .string()
    .trim()
    .min(1, "Profile name is required")
    .max(200, "Profile name must be at most 200 characters"),
  // Optional editable fields — all match existing Prisma column types
  status: z.enum(["Active", "Archived"]).optional(),
  accountStatus: z
    .enum(["Active", "EmailUnverified", "Suspended"])
    .optional(),
  targetRoles: optionalText,
  experienceLevel: z
    .enum(["entry", "mid", "senior", "other"])
    .optional(),
  skillsOfInterest: optionalText,
  institution: optionalString,
  degree: optionalString,
  fieldOfStudy: optionalString,
  currentAcademicLevel: optionalString,
  expectedGraduationDate: z
    .string()
    .datetime({ offset: true })
    .nullable()
    .optional(),
  itIndustrialTrainingRequired: z.boolean().optional(),
  itIndustrialTrainingDetails: optionalText,
  internshipDuration: optionalString,
  internshipStartDate: z
    .string()
    .datetime({ offset: true })
    .nullable()
    .optional(),
  internshipEndDate: z
    .string()
    .datetime({ offset: true })
    .nullable()
    .optional(),
  workArrangementPreference: z
    .enum(["Remote", "Hybrid", "OnSite", "Unknown"])
    .optional(),
  employmentTypePreference: z
    .string()
    .trim()
    .min(1, "Must not be empty")
    .max(500, "Must be at most 500 characters")
    .optional(),
  salaryMin: z.number().int().min(0).nullable().optional(),
  salaryMax: z.number().int().min(0).nullable().optional(),
  salaryCurrency: z
    .string()
    .trim()
    .max(10, "Must be at most 10 characters")
    .optional(),
  countries: optionalText,
  locations: optionalText,
  relocationPreference: z
    .enum(["willing", "not_willing", "with_conditions"])
    .optional(),
  relocationNotes: optionalText,
  otherPreferences: optionalText,
  activeCvId: z
    .string()
    .max(200, "Must be at most 200 characters")
    .nullable()
    .optional(),
});

export type CreateProfileInput = z.infer<typeof createProfileSchema>;

// ── Update (PATCH) profile ──────────────────────────────────────────────────

export const updateProfileSchema = createProfileSchema.partial();

export type UpdateProfileInput = z.infer<typeof updateProfileSchema>;

// ── Path parameter validation ───────────────────────────────────────────────
// Profile IDs are UUIDs generated by Prisma. Reject malformed IDs with 400
// rather than issuing a pointless database query.
export const profileIdSchema = z.string().uuid("Invalid profile ID");

// ── Response mapper ─────────────────────────────────────────────────────────
// Converts a Prisma Profile record to a safe public snapshot.
// Converts Date fields to ISO strings. Excludes internal fields (userId).

export interface ProfilePublic {
  id: string;
  name: string;
  status: string;
  accountStatus: string | null;
  targetRoles: string | null;
  experienceLevel: string | null;
  skillsOfInterest: string | null;
  institution: string | null;
  degree: string | null;
  fieldOfStudy: string | null;
  currentAcademicLevel: string | null;
  expectedGraduationDate: string | null;
  itIndustrialTrainingRequired: boolean;
  itIndustrialTrainingDetails: string | null;
  internshipDuration: string | null;
  internshipStartDate: string | null;
  internshipEndDate: string | null;
  workArrangementPreference: string;
  employmentTypePreference: string;
  salaryMin: number | null;
  salaryMax: number | null;
  salaryCurrency: string;
  countries: string | null;
  locations: string | null;
  relocationPreference: string;
  relocationNotes: string | null;
  otherPreferences: string | null;
  activeCvId: string | null;
  createdAt: string;
  updatedAt: string;
}

export function mapProfile(profile: {
  id: string;
  name: string;
  status: string;
  accountStatus: string | null;
  targetRoles: string | null;
  experienceLevel: string | null;
  skillsOfInterest: string | null;
  institution: string | null;
  degree: string | null;
  fieldOfStudy: string | null;
  currentAcademicLevel: string | null;
  expectedGraduationDate: Date | null;
  itIndustrialTrainingRequired: boolean;
  itIndustrialTrainingDetails: string | null;
  internshipDuration: string | null;
  internshipStartDate: Date | null;
  internshipEndDate: Date | null;
  workArrangementPreference: string;
  employmentTypePreference: string;
  salaryMin: number | null;
  salaryMax: number | null;
  salaryCurrency: string;
  countries: string | null;
  locations: string | null;
  relocationPreference: string;
  relocationNotes: string | null;
  otherPreferences: string | null;
  activeCvId: string | null;
  createdAt: Date;
  updatedAt: Date;
}): ProfilePublic {
  return {
    id: profile.id,
    name: profile.name,
    status: profile.status,
    accountStatus: profile.accountStatus,
    targetRoles: profile.targetRoles,
    experienceLevel: profile.experienceLevel,
    skillsOfInterest: profile.skillsOfInterest,
    institution: profile.institution,
    degree: profile.degree,
    fieldOfStudy: profile.fieldOfStudy,
    currentAcademicLevel: profile.currentAcademicLevel,
    expectedGraduationDate: profile.expectedGraduationDate?.toISOString() ?? null,
    itIndustrialTrainingRequired: profile.itIndustrialTrainingRequired,
    itIndustrialTrainingDetails: profile.itIndustrialTrainingDetails,
    internshipDuration: profile.internshipDuration,
    internshipStartDate: profile.internshipStartDate?.toISOString() ?? null,
    internshipEndDate: profile.internshipEndDate?.toISOString() ?? null,
    workArrangementPreference: profile.workArrangementPreference,
    employmentTypePreference: profile.employmentTypePreference,
    salaryMin: profile.salaryMin,
    salaryMax: profile.salaryMax,
    salaryCurrency: profile.salaryCurrency,
    countries: profile.countries,
    locations: profile.locations,
    relocationPreference: profile.relocationPreference,
    relocationNotes: profile.relocationNotes,
    otherPreferences: profile.otherPreferences,
    activeCvId: profile.activeCvId,
    createdAt: profile.createdAt.toISOString(),
    updatedAt: profile.updatedAt.toISOString(),
  };
}
